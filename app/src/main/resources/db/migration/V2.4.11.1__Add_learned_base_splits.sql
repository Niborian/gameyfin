CREATE TABLE LEARNED_BASE_SPLIT (
    ID VARCHAR(90) PRIMARY KEY,
    LIBRARY_ID BIGINT NOT NULL REFERENCES LIBRARY(ID) ON DELETE CASCADE,
    TEMPLATE CLOB NOT NULL,
    STREAK INTEGER NOT NULL,
    NEXT_OFFER INTEGER NOT NULL,
    -- CASE remains valid after the H2 Flyway connection closes.
    MODE VARCHAR(16) NOT NULL CHECK (CASE MODE
        WHEN 'REVIEW' THEN TRUE WHEN 'AUTOMATIC' THEN TRUE WHEN 'MUTED' THEN TRUE ELSE FALSE END)
);

CREATE INDEX IDX_LEARNED_BASE_SPLIT_LIBRARY ON LEARNED_BASE_SPLIT(LIBRARY_ID, MODE);

CREATE TABLE LEARNED_BASE_SPLIT_DECISION (
    RULE_ID VARCHAR(90) NOT NULL REFERENCES LEARNED_BASE_SPLIT(ID) ON DELETE CASCADE,
    GAME_ID BIGINT NOT NULL REFERENCES GAME(ID) ON DELETE CASCADE,
    APPROVED BOOLEAN NOT NULL,
    PRIMARY KEY (RULE_ID, GAME_ID)
);
