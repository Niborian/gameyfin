-- Metadata-only, no updates to existing variant identities, paths, defaults or build fields.
CREATE TABLE VARIANT_DETAILS (
    VARIANT_ID BIGINT NOT NULL PRIMARY KEY,
    GAME_ID BIGINT NOT NULL,
    STORE VARCHAR(255) NOT NULL DEFAULT 'UNKNOWN',
    STORE_PRODUCT_ID VARCHAR(255),
    EDITION VARCHAR(255),
    LIBRARY_VERSION VARCHAR(255),
    BUILD_ID VARCHAR(255),
    MANUAL_OVERRIDE BOOLEAN NOT NULL DEFAULT FALSE,
    REVISION BIGINT NOT NULL DEFAULT 0,
    SOURCE VARCHAR(255),
    EVIDENCE CLOB,
    OBSERVED_AT TIMESTAMP(6) WITH TIME ZONE,
    ACTOR VARCHAR(255),
    CONSTRAINT FK_VARIANT_DETAILS_VARIANT FOREIGN KEY (VARIANT_ID) REFERENCES GAME_VARIANT(ID) ON DELETE CASCADE,
    CONSTRAINT CK_VARIANT_DETAILS_REVISION CHECK (REVISION >= 0)
);
