-- Exact optional distribution ownership, separate from approved acquisition.
-- No cascading deletion and no active provider/configuration change.
CREATE TABLE QB_DISTRIBUTION_INTENT (
    ID UUID NOT NULL PRIMARY KEY,
    CLIENT_ID UUID NOT NULL,
    SNAPSHOT_ID UUID NOT NULL REFERENCES OWNED_SNAPSHOT_RECORD(ID),
    LEASE_ID UUID NOT NULL REFERENCES OWNED_SNAPSHOT_LEASE_RECORD(ID),
    MANIFEST_DIGEST VARCHAR(64) NOT NULL,
    MAPPING_DIGEST VARCHAR(64) NOT NULL,
    STATE VARCHAR(24) NOT NULL,
    TASK_ID VARCHAR(128),
    INFO_HASH VARCHAR(40),
    METADATA BLOB,
    UPDATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    REVISION BIGINT NOT NULL,
    CONSTRAINT UK_QB_DISTRIBUTION_SNAPSHOT UNIQUE (CLIENT_ID, SNAPSHOT_ID),
    CONSTRAINT CK_QB_DISTRIBUTION_STATE CHECK (CASE STATE
        WHEN 'RESERVED' THEN TRUE WHEN 'CREATING' THEN TRUE WHEN 'CREATED' THEN TRUE
        WHEN 'VALIDATED' THEN TRUE WHEN 'ADDING' THEN TRUE WHEN 'STOPPED' THEN TRUE
        WHEN 'CHECKING' THEN TRUE WHEN 'STARTING' THEN TRUE WHEN 'SEEDING' THEN TRUE
        WHEN 'STOPPING' THEN TRUE WHEN 'REMOVING' THEN TRUE WHEN 'REMOVED' THEN TRUE
        WHEN 'CANCELLING' THEN TRUE WHEN 'CANCELLED' THEN TRUE
        WHEN 'UNCERTAIN' THEN TRUE ELSE FALSE END),
    CONSTRAINT CK_QB_DISTRIBUTION_DIGESTS CHECK (
        REGEXP_LIKE(MANIFEST_DIGEST, '^[0-9a-f]{64}$') AND REGEXP_LIKE(MAPPING_DIGEST, '^[0-9a-f]{64}$')
    ),
    CONSTRAINT CK_QB_DISTRIBUTION_TASK CHECK (TASK_ID IS NULL OR REGEXP_LIKE(TASK_ID, '^[A-Za-z0-9-]{1,128}$')),
    CONSTRAINT CK_QB_DISTRIBUTION_HASH CHECK (INFO_HASH IS NULL OR REGEXP_LIKE(INFO_HASH, '^[0-9a-f]{40}$')),
    CONSTRAINT CK_QB_DISTRIBUTION_METADATA CHECK (METADATA IS NULL OR OCTET_LENGTH(METADATA) BETWEEN 1 AND 1048576),
    CONSTRAINT CK_QB_DISTRIBUTION_VALIDATED CHECK (CASE STATE
        WHEN 'VALIDATED' THEN TASK_ID IS NOT NULL AND INFO_HASH IS NOT NULL AND METADATA IS NOT NULL
        WHEN 'ADDING' THEN TASK_ID IS NOT NULL AND INFO_HASH IS NOT NULL AND METADATA IS NOT NULL
        WHEN 'STOPPED' THEN TASK_ID IS NOT NULL AND INFO_HASH IS NOT NULL AND METADATA IS NOT NULL
        WHEN 'CHECKING' THEN TASK_ID IS NOT NULL AND INFO_HASH IS NOT NULL AND METADATA IS NOT NULL
        WHEN 'STARTING' THEN TASK_ID IS NOT NULL AND INFO_HASH IS NOT NULL AND METADATA IS NOT NULL
        WHEN 'SEEDING' THEN TASK_ID IS NOT NULL AND INFO_HASH IS NOT NULL AND METADATA IS NOT NULL
        WHEN 'STOPPING' THEN TASK_ID IS NOT NULL AND INFO_HASH IS NOT NULL AND METADATA IS NOT NULL
        WHEN 'REMOVING' THEN TASK_ID IS NOT NULL AND INFO_HASH IS NOT NULL AND METADATA IS NOT NULL
        WHEN 'REMOVED' THEN TASK_ID IS NOT NULL AND INFO_HASH IS NOT NULL AND METADATA IS NOT NULL
        -- A RESERVED intent that never invoked creator/add can cancel with no task.
        -- The lifecycle proves that exact lineage; unknown CREATING stays retained.
        WHEN 'CANCELLING' THEN TRUE
        WHEN 'CANCELLED' THEN TRUE
        ELSE TRUE END)
);
