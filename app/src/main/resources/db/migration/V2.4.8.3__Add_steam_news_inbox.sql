ALTER TABLE GAME_VARIANT ADD STEAM_NEWS_WATCH_ENABLED BOOLEAN NOT NULL DEFAULT TRUE;
CREATE TABLE STEAM_NEWS_CHECK (
    APP_ID VARCHAR(20) PRIMARY KEY,
    ATTEMPTED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    SUCCEEDED_AT TIMESTAMP WITH TIME ZONE,
    FAILED BOOLEAN NOT NULL
);
CREATE TABLE STEAM_NEWS_NOTICE (
    APP_ID VARCHAR(20) NOT NULL,
    EVENT_ID VARCHAR(32) NOT NULL,
    TITLE VARCHAR(512) NOT NULL,
    EVENT_URL VARCHAR(2048) NOT NULL,
    PUBLISHED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    OBSERVED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    CLASSIFICATION VARCHAR(32) NOT NULL,
    REASON VARCHAR(512) NOT NULL,
    SOURCE VARCHAR(128) NOT NULL,
    FEED_NAME VARCHAR(256) NOT NULL,
    FEED_LABEL VARCHAR(256) NOT NULL,
    TAGS VARCHAR(2048) NOT NULL,
    IGNORED BOOLEAN NOT NULL DEFAULT FALSE,
    SNOOZED_UNTIL TIMESTAMP WITH TIME ZONE,
    PRIMARY KEY(APP_ID, EVENT_ID)
);
CREATE INDEX STEAM_NEWS_NOTICE_PUBLISHED ON STEAM_NEWS_NOTICE(PUBLISHED_AT);
CREATE INDEX GAME_VARIANT_STEAM_WATCH ON GAME_VARIANT(STEAM_APP_ID,STEAM_APP_ID_VERIFIED_AT);
